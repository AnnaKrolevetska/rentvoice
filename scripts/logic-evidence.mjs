// Runs the booking-logic scenarios and writes evidence/logic-checks.md
// with the expected outcome, every tool call + result, and the DB before/after.
process.env.APP_TODAY ||= '2026-10-01';
import fs from 'node:fs';

const { SCENARIOS, runScenario } = await import('./scenarios.js');

const table = (rows) => {
  if (!rows.length) return '_(none)_\n';
  const cols = ['id', 'equipment_id', 'quantity', 'start_date', 'end_date', 'source_draft_id'];
  return `| ${cols.join(' | ')} |\n|${cols.map(() => '---').join('|')}|\n`
    + rows.map((r) => `| ${cols.map((c) => r[c] ?? '').join(' | ')} |`).join('\n') + '\n';
};

const short = (res) => {
  const pick = ['ok', 'available', 'draft_created', 'superseded_previous', 'free_units', 'duplicate', 'error', 'remaining_for_these_dates'];
  const o = {};
  for (const k of pick) if (k in res) o[k] = res[k];
  if (res.draft) o.draft_id = res.draft.draft_id;
  if (res.booking) o.booking_id = res.booking.booking_id;
  if (res.alternatives) o.alternatives = res.alternatives;
  if (res.errors) o.errors = res.errors.map((e) => e.code);
  return JSON.stringify(o);
};

let md = `# Booking-logic checks (DB before / after)\n\nGenerated by \`npm run evidence\` on ${new Date().toISOString()} with APP_TODAY=${process.env.APP_TODAY}.\n`
  + `Each run starts from the seeded database (inventory + BK-SEED-001 Camera A 10–12 Oct 2026).\n`
  + `These replay the exact tool calls the voice agent makes; the spoken versions are in voice-eval reports.\n\n`;
let passed = 0;
const results = SCENARIOS.map(runScenario);
md += `| ID | Check | Result |\n|---|---|---|\n` + results.map((r) => `| ${r.id} | ${r.title} | ${r.pass ? 'PASS' : 'FAIL'} |`).join('\n') + '\n\n';

for (const r of results) {
  if (r.pass) passed++;
  md += `## ${r.id} — ${r.title}: ${r.pass ? 'PASS' : 'FAIL'}\n\n`;
  md += `**User says:** ${r.utterances.map((u) => `“${u}”`).join(' → ')}\n\n`;
  md += `**Expected (written before running):** ${r.expected}\n\n`;
  md += `**Tool calls:**\n\n| user turn | source | tool | args | result |\n|---|---|---|---|---|\n`;
  md += r.steps.map((s) => `| ${s.turn} | ${s.source} | ${s.name} | \`${JSON.stringify(s.args)}\` | \`${short(s.result)}\` |`).join('\n') + '\n\n';
  md += `**Bookings BEFORE (${r.before.booking_count} rows):**\n\n${table(r.before.bookings)}\n`;
  md += `**Bookings AFTER (${r.after.booking_count} rows):**\n\n${table(r.after.bookings)}\n`;
}

fs.mkdirSync('evidence', { recursive: true });
fs.writeFileSync('evidence/logic-checks.md', md);
console.log(`${passed}/${results.length} scenarios passed → evidence/logic-checks.md`);
process.exitCode = passed === results.length ? 0 : 1;
